export function getDistrictObjectsByDivision(divisionName?: string): BdDistrict[] {
  if (!divisionName) return [];
  return BD_DIVISIONS.find((d) => d.name === divisionName)?.districts || [];
}

export function getDistrictsByDivision(divisionName?: string): string[] {
  return getDistrictObjectsByDivision(divisionName).map((d) => d.name);
}

export function getUpazilasByDistrict(divisionName?: string, districtName?: string): string[] {
  if (!divisionName || !districtName) return [];
  const div = BD_DIVISIONS.find((d) => d.name === divisionName);
  return div?.districts.find((dist) => dist.name === districtName)?.upazilas || [];
}
